import { AbsoluteFill, Audio, Sequence, interpolate, staticFile } from 'remotion';
import { C } from './theme';
import { Hook } from './scenes/Hook';
import { Intro } from './scenes/Intro';
import { Rewards } from './scenes/Rewards';
import { Schedule } from './scenes/Schedule';
import { Claim } from './scenes/Claim';
import { Profile } from './scenes/Profile';
import { Agents } from './scenes/Agents';
import { Outro } from './scenes/Outro';

// Scene list in frames @30fps; the script lives in the scene files' header comments.
export const SCENES = [
  [Hook, 90],
  [Intro, 90],
  [Rewards, 180],
  [Schedule, 150],
  [Claim, 180],
  [Profile, 120],
  [Agents, 240],
  [Outro, 150],
];
export const DURATION = SCENES.reduce((s, [, d]) => s + d, 0);

export function Promo() {
  let from = 0;
  return (
    <AbsoluteFill style={{ background: C.bg }}>
      {/* Generated by scripts/music.mjs, synced to the scene cuts above. */}
      <Audio
        src={staticFile('music.wav')}
        volume={(f) => interpolate(f, [DURATION - 30, DURATION], [1, 0], { extrapolateLeft: 'clamp', extrapolateRight: 'clamp' })}
      />
      {SCENES.map(([Scene, d]) => {
        const seq = (
          <Sequence key={Scene.name} from={from} durationInFrames={d}>
            <Scene />
          </Sequence>
        );
        from += d;
        return seq;
      })}
    </AbsoluteFill>
  );
}
