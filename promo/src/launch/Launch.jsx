import { AbsoluteFill, Audio, Sequence, interpolate, staticFile } from 'remotion';
import { C } from '../theme';
import { Stub } from './Stub';
import { Countdown } from './Countdown';
import { LiveOnBase } from './LiveOnBase';

// Launch teaser: stub with the date → countdown → today 15:00 UTC on Base. Frames @30fps.
export const LAUNCH_SCENES = [
  [Stub, 150],
  [Countdown, 150],
  [LiveOnBase, 150],
];
export const LAUNCH_DURATION = LAUNCH_SCENES.reduce((s, [, d]) => s + d, 0);

export function Launch() {
  let from = 0;
  return (
    <AbsoluteFill style={{ background: C.bg }}>
      {/* Generated by scripts/music-launch.mjs, synced to the scenes above. */}
      <Audio
        src={staticFile('launch/music.wav')}
        volume={(f) => interpolate(f, [LAUNCH_DURATION - 20, LAUNCH_DURATION], [1, 0], { extrapolateLeft: 'clamp', extrapolateRight: 'clamp' })}
      />
      {LAUNCH_SCENES.map(([Scene, d]) => {
        const seq = (
          <Sequence key={Scene.name} from={from} durationInFrames={d}>
            <Scene />
          </Sequence>
        );
        from += d;
        return seq;
      })}
    </AbsoluteFill>
  );
}
